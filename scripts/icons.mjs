/**
 * Generates the icon names the validator checks against and the lazy loaders the renderer draws
 * with, from the installed icon packages. Run after bumping lucide-react, @lobehub/icons or
 * @icons-pack/react-simple-icons: `node scripts/icons.mjs`.
 */
import { readdirSync, readFileSync, writeFileSync } from 'node:fs';
import { createRequire } from 'node:module';
import { dirname, join } from 'node:path';

const require = createRequire(import.meta.url);
const packageDir = (name) => dirname(require.resolve(`${name}/package.json`));

// Lucide: the names its own dynamic loader knows.
const lucideSource = readFileSync(
  join(packageDir('lucide-react'), 'dist/esm/dynamicIconImports.mjs'),
  'utf8',
);
const lucide = [...lucideSource.matchAll(/^\s+"([\da-z-]+)": \(\) => import/gm)].map((m) => m[1]);

// Simple Icons: one module per brand, `Si<Name>`; the slug is the lowercase name.
const simple = readdirSync(join(packageDir('@icons-pack/react-simple-icons'), 'icons'))
  .filter((file) => file.endsWith('.mjs'))
  .map((file) => file.slice(0, -4))
  .map((module) => ({ module, slug: module.slice(2).toLowerCase() }));

// LobeHub Icons: the ids in its table of contents.
const tocSource = readFileSync(join(packageDir('@lobehub/icons'), 'es/toc2.mjs'), 'utf8');
const lobehub = [...new Set([...tocSource.matchAll(/"id": "([^"]+)"/g)].map((m) => m[1]))];

const header = '// Generated by scripts/icons.mjs from the installed icon packages. Do not edit.\n';

writeFileSync(
  'src/icons/names.ts',
  `${header}
/** Lucide icon names, space separated. */
export const LUCIDE_NAMES = '${lucide.join(' ')}';

/** Simple Icons slugs, space separated. */
export const SIMPLE_NAMES = '${simple.map((icon) => icon.slug).join(' ')}';

/** LobeHub Icons ids, space separated. */
export const LOBEHUB_NAMES = '${lobehub.join(' ')}';
`,
);

writeFileSync(
  'src/react/icons/simpleLoaders.ts',
  `${header}
import type { IconLoader } from './types';

/** One lazy chunk per brand, so a card pulls only the logos it shows. */
const loaders: Record<string, IconLoader> = {
${simple
  .map(
    (icon) =>
      `  '${icon.slug}': () => import('@icons-pack/react-simple-icons/icons/${icon.module}'),`,
  )
  .join('\n')}
};

export default loaders;
`,
);

writeFileSync(
  'src/react/icons/lobehubLoaders.ts',
  `${header}
import type { IconLoader } from './types';

/** One lazy chunk per provider or model icon. */
const loaders: Record<string, IconLoader> = {
${lobehub.map((id) => `  '${id}': () => import('@lobehub/icons/es/${id}'),`).join('\n')}
};

export default loaders;
`,
);

console.log(`lucide ${lucide.length}, simple ${simple.length}, lobehub ${lobehub.length}`);
