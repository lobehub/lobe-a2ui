/**
 * Generates the icon names the validator checks against, and the package versions the renderer
 * fetches SVGs from, out of the installed static icon packages. Run after bumping lucide-static,
 * simple-icons or @lobehub/icons-static-svg: `node scripts/icons.mjs`.
 */
import { readdirSync, readFileSync, writeFileSync } from 'node:fs';
import { join } from 'node:path';

const packageDir = (name) => join('node_modules', name);
const versionOf = (name) =>
  JSON.parse(readFileSync(join(packageDir(name), 'package.json'), 'utf8')).version;
const svgNames = (name) =>
  readdirSync(join(packageDir(name), 'icons'))
    .filter((file) => file.endsWith('.svg'))
    .map((file) => file.slice(0, -4))
    .sort();

const lucide = svgNames('lucide-static');
const simple = svgNames('simple-icons');
// LobeHub ships `<id>.svg` plus variants (`-color`, `-text`, `-brand`...); the ids are the plain ones.
const lobehubFiles = new Set(svgNames('@lobehub/icons-static-svg'));
const lobehub = [...lobehubFiles].filter(
  (file) => !/-(color|text|brand|brand-color|text-cn|combine|combine-color|avatar)$/.test(file),
);

const header = '// Generated by scripts/icons.mjs from the installed icon packages. Do not edit.\n';

writeFileSync(
  'src/icons/packages.ts',
  `${header}
/** The static icon packages the renderer fetches SVGs from, at the versions the names come from. */
export const ICON_PACKAGES = {
  lobehub: { pkg: '@lobehub/icons-static-svg', version: '${versionOf('@lobehub/icons-static-svg')}' },
  lucide: { pkg: 'lucide-static', version: '${versionOf('lucide-static')}' },
  simple: { pkg: 'simple-icons', version: '${versionOf('simple-icons')}' },
} as const;
`,
);

writeFileSync(
  'src/icons/names.ts',
  `${header}
/** Lucide icon names, space separated. */
export const LUCIDE_NAMES = '${lucide.join(' ')}';

/** Simple Icons slugs, space separated. */
export const SIMPLE_NAMES = '${simple.join(' ')}';

/** LobeHub Icons ids (lowercase, as their files are named), space separated. */
export const LOBEHUB_NAMES = '${lobehub.join(' ')}';
`,
);

console.log(`lucide ${lucide.length}, simple ${simple.length}, lobehub ${lobehub.length}`);
