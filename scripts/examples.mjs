/**
 * Generates `src/examples/index.ts`, which imports every example surface under
 * `src/examples/<catalog>/<version>/*.json`, the way the official SDK's `load_examples` reads an
 * examples directory. Run after adding or removing an example: `node scripts/examples.mjs`.
 */
import { readdirSync, writeFileSync } from 'node:fs';

const root = 'src/examples';
const catalogs = readdirSync(root, { withFileTypes: true }).filter((entry) => entry.isDirectory());
const imports = [];
const tables = [];
for (const catalog of catalogs) {
  for (const version of readdirSync(`${root}/${catalog.name}`)) {
    const files = readdirSync(`${root}/${catalog.name}/${version}`)
      .filter((file) => file.endsWith('.json'))
      .sort();
    const entries = files.map((file) => {
      const id = file.slice(0, -5);
      const local = `${catalog.name}_${id.replaceAll(/\W/g, '_')}`;
      imports.push(`import ${local} from './${catalog.name}/${version}/${file}';`);
      return `  { ...${local}, catalog: '${catalog.name}', id: '${id}' },`;
    });
    tables.push(`  ${catalog.name}: [\n${entries.join('\n')}\n  ],`);
  }
}
writeFileSync(
  `${root}/index.ts`,
  `// Generated by scripts/examples.mjs. Do not edit.
/* eslint-disable simple-import-sort/imports */
import type { A2uiExample } from './types';
${imports.join('\n')}

/** Every example surface, by catalog: the official basic examples and LobeHub's. */
export const A2UI_EXAMPLES = {
${tables.join('\n')}
} as Record<'basic' | 'lobehub', A2uiExample[]>;
`,
);
