/**
 * Writes the default system prompts as plain strings (`src/systemPrompt.ts`), so a host can show
 * them, e.g. in a client tool manifest, without bundling the schemas, examples and validator that
 * generate them. Run after changing the catalog, examples or prompt: `bun scripts/prompt.ts`.
 * A test fails when the file is stale.
 */
import { writeFileSync } from 'node:fs';

import { buildA2uiSystemPrompt } from '../src/processor';

const tool = buildA2uiSystemPrompt({ delivery: 'tool' });
const cli = buildA2uiSystemPrompt({ delivery: 'cli' });

writeFileSync(
  'src/systemPrompt.ts',
  `// Generated by scripts/prompt.ts from the catalog, examples and prompt. Do not edit.

/** The system prompt for an Agent that draws cards with the renderUI tool. */
export const A2UI_SYSTEM_PROMPT: string = ${JSON.stringify(tool)};

/** The system prompt for an external runtime that draws cards with \`lh card render\`. */
export const A2UI_CLI_SYSTEM_PROMPT: string = ${JSON.stringify(cli)};
`,
);
console.log(`tool ${tool.length} chars, cli ${cli.length} chars`);
